/// [dayCount]일째에 보여줄 글귀. 두 사람이 같은 날 같은 글귀를 보고, 날이 바뀌면 다음 글귀로 넘어간다.
String dailyMessageFor(int dayCount) {
  final index = dayCount % dailyMessages.length;
  return dailyMessages[index].replaceAll('{days}', '$dayCount');
}
